-- Premium price and odds alerts: a reader picks a prediction market on a pin
-- (any outcome moving) or a stock, and a size of move; the server tells them
-- (bell + browser push) when it has moved more than that since the last time
-- they were told. Markets move in percentage points of chance, stocks in
-- percent of price.
--
-- "baseline" is what the move is measured from: { "<outcome label>": points }
-- for a market, { "price": dollars } for a stock. Telling the reader resets it
-- to the value they were told, so one swing is one alert, and the claim on the
-- old baseline is what keeps it to one alert however many servers see it due.

CREATE TABLE "MoveAlert" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"             integer NOT NULL REFERENCES "User" ("id") ON DELETE CASCADE,
  "kind"               varchar(8) NOT NULL CHECK ("kind" IN ('market', 'stock')),
  -- marketRefKey (k:/p:/u:...) of the market, or the upper-case ticker symbol.
  "subject"            varchar(200) NOT NULL,
  "label"              varchar(300) NOT NULL,
  -- The pin the alert was set on: where the notification leads.
  -- A market's link, as parsed from the pin's own links (never from the request).
  "ref"                jsonb,
  "pinId"              integer REFERENCES "Pin" ("id") ON DELETE CASCADE,
  -- Points (market) or percent (stock) the value must move by, more than.
  "threshold"          numeric(6, 2) NOT NULL CHECK ("threshold" > 0 AND "threshold" <= 100),
  "baseline"           jsonb,
  "utcLastAlertDateTime" timestamptz,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  "utcDeletedDateTime" timestamptz,
  CONSTRAINT "UC_MoveAlert_subject" UNIQUE ("userId", "kind", "subject")
);
CREATE INDEX "IX_MoveAlert_live" ON "MoveAlert" ("kind", "subject") WHERE "utcDeletedDateTime" IS NULL;
CREATE INDEX "IX_MoveAlert_pin" ON "MoveAlert" ("userId", "pinId") WHERE "utcDeletedDateTime" IS NULL;

-- A 'move' notification carries what moved: { kind, label, from, to, unit }.
ALTER TABLE "Notification" ADD COLUMN "move" jsonb;
