-- Life phases, each with an octagon profile: "early career", "president, first
-- term". Eight axes (src/lib/people.ts OCTAGON_AXES), each scored 0..5 against
-- a written rubric from documented evidence, with the evidence URL and a
-- confidence:
--   education  highest attainment reached by then
--   wealth     net worth or income against national thresholds of the time
--   position   scope of the role held
--   standing   public approval or favourability, where it was measured
--   health     documented health, where an examination or disclosure exists
--   misconduct the documented legal and ethics record within the phase (0154):
--              more = more documented misconduct
--   social     assessed effects on health, safety, education, rights, environment
--   economic   assessed effects on efficiency, growth, fiscal sustainability (0156)
-- An axis with no evidence is absent - drawn as a gap, never as zero. There is
-- no total and no ideal shape: it is a profile, not a ranking.
-- Appearance and personality, which the "hexagonal human" chart this was
-- modelled on includes, are not axes: they cannot be scored from evidence.
CREATE TABLE "PersonPhase" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"           integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "label"              varchar(80) NOT NULL,
  "startYear"          smallint CONSTRAINT "CK_PersonPhase_start" CHECK ("startYear" BETWEEN 1500 AND 2200),
  "endYear"            smallint CONSTRAINT "CK_PersonPhase_end" CHECK ("endYear" BETWEEN 1500 AND 2200),
  -- What the phase was, in a sentence.
  "summary"            text,
  -- { education: { score, basis, evidenceUrl, confidence }, ... }
  "axes"               jsonb NOT NULL,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonPhase_years" CHECK ("startYear" IS NULL OR "endYear" IS NULL OR "endYear" >= "startYear"),
  CONSTRAINT "UC_PersonPhase_label" UNIQUE ("personId", "label")
);
CREATE INDEX "IX_PersonPhase_personId" ON "PersonPhase" ("personId", "startYear");
