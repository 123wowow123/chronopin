-- The track record of the prediction markets behind Predicted pins: the odds
-- each market gave when the pin first cited it, and how it settled
-- (src/server/services/predictionRecords.ts, shown on /predictions).
--
-- One row per pin and market. "outcomes" is the market's outcomes and chances
-- as first read ([{label, probability}], 0-1) and is never rewritten, so the
-- page scores the odds the pin was written with rather than what the market
-- drifted to. A market already settled when first seen is not recorded: its
-- odds before the settlement are unknown.
--
-- status: open (still trading), resolved (settled; "finalOutcomes" holds the
-- settled chances) or void (closed without a decisive result).
CREATE TABLE "PredictionRecord" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "pinId"              integer NOT NULL REFERENCES "Pin" ("id") ON DELETE CASCADE,
  "marketUrl"          text NOT NULL,
  "source"             varchar(20) NOT NULL CHECK ("source" IN ('Kalshi', 'Polymarket', 'Polymarket US')),
  "question"           text NOT NULL,
  "outcomes"           jsonb NOT NULL,
  "volume"             double precision CHECK ("volume" IS NULL OR "volume" >= 0),
  "closeTime"          timestamptz,
  "status"             varchar(10) NOT NULL DEFAULT 'open' CHECK ("status" IN ('open', 'resolved', 'void')),
  "finalOutcomes"      jsonb,
  "utcSnapshotDateTime" timestamptz NOT NULL DEFAULT now(),
  "utcResolvedDateTime" timestamptz,
  CONSTRAINT "UQ_PredictionRecord_pin_market" UNIQUE ("pinId", "marketUrl")
);

CREATE INDEX "IX_PredictionRecord_status" ON "PredictionRecord" ("status");
