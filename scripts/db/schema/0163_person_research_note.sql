-- What was looked for and what was found, per person and topic, so the wiki
-- can say how far a search went instead of leaving an empty section that reads
-- as "nothing there". One row per person and topic, the latest search winning:
--   legal      matters before a court, regulator or ethics body (0154)
--   standing   public approval from a pollster (octagon axis, 0161)
--   society    effects of what they did, assessed from cited evidence (0156)
--   education  the highest degree (0162)
--   wealth     income and net worth (0162)
--   other
-- "coverage" says how complete the search was:
--   searched   a real search of official sources was made
--   partial    a search was made but the sources it needed were blocked,
--              paywalled or ran out of budget - so "nothing found" is weak
--   not-found  nothing documented exists for this topic (e.g. no poll in era)
-- Not a source of facts: a fact still needs its own cited row elsewhere.
CREATE TABLE "PersonResearchNote" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"           integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "topic"              varchar(16) NOT NULL CONSTRAINT "CK_PersonResearchNote_topic" CHECK ("topic" IN ('legal', 'standing', 'society', 'education', 'wealth', 'other')),
  "coverage"           varchar(12) NOT NULL DEFAULT 'searched' CONSTRAINT "CK_PersonResearchNote_coverage" CHECK ("coverage" IN ('searched', 'partial', 'not-found')),
  "checkedDate"        date NOT NULL DEFAULT now()::date,
  -- What was searched, what was found and what stayed a gap, in plain words.
  "note"               text NOT NULL,
  -- Pages that were looked at but could not be cited (blocked, unreadable,
  -- a relay): [{ "url": "https://...", "why": "403" }]. Never cited as fact.
  "unciteable"         jsonb NOT NULL DEFAULT '[]'::jsonb,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "UC_PersonResearchNote_topic" UNIQUE ("personId", "topic")
);
CREATE INDEX "IX_PersonResearchNote_personId" ON "PersonResearchNote" ("personId");
