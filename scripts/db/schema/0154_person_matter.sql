-- A person's legal and ethics record: insider trading and other securities
-- violations, corruption, fraud, tax and campaign-finance cases, congressional
-- ethics findings, and similar misconduct. This is the most sensitive thing a
-- page states about a real person, so the table is strict:
--   * a matter exists only where an official body or a court ACTED (a
--     charge, an indictment, a complaint, a finding, a settlement, a
--     conviction, a sanction), or a reputable outlet reported that official
--     action. A rumour, an accusation in an interview or a lawsuit's unproven
--     claim by a private party is not a matter;
--   * every row names its `status` - what the body or court actually did, and
--     where it ended - so a charge is never read as a conviction, and an
--     acquittal, a dismissal or a closed investigation is listed as such;
--   * every row has a source URL (the order, press release, docket or report,
--     or the outlet that reported it).
CREATE TABLE "PersonMatter" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"           integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "kind"               varchar(24) NOT NULL DEFAULT 'other',
  "title"              varchar(400) NOT NULL,
  -- What it concerned, in neutral words.
  "summary"            text,
  -- Where it stands, or how it ended. The page shows this first.
  "status"             varchar(24) NOT NULL,
  -- Who acted: "U.S. Securities and Exchange Commission", "U.S. District Court, S.D.N.Y.",
  -- "House Committee on Ethics".
  "authority"          varchar(200),
  -- The day it was filed / opened, and the day it was decided or closed.
  "filedDate"          date,
  "resolvedDate"       date,
  -- A fine, sentence or settlement as the order states it ("$2.7M civil penalty").
  "penalty"            text,
  "sourceUrl"          text NOT NULL,
  -- The day the status was last checked against its source.
  "asOf"               date,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonMatter_kind" CHECK ("kind" IN (
    'insider-trading', 'securities', 'corruption', 'fraud', 'tax', 'campaign-finance', 'ethics', 'obstruction', 'misconduct', 'other')),
  CONSTRAINT "CK_PersonMatter_status" CHECK ("status" IN (
    'investigated', 'charged', 'convicted', 'pleaded-guilty', 'acquitted', 'dismissed', 'closed-no-action',
    'settled', 'found-liable', 'sanctioned', 'pardoned', 'overturned')),
  CONSTRAINT "CK_PersonMatter_dates" CHECK ("resolvedDate" IS NULL OR "filedDate" IS NULL OR "resolvedDate" >= "filedDate"),
  CONSTRAINT "CK_PersonMatter_source" CHECK ("sourceUrl" LIKE 'https://%'),
  CONSTRAINT "UC_PersonMatter_title_authority" UNIQUE ("personId", "title", "authority")
);
CREATE INDEX "IX_PersonMatter_personId" ON "PersonMatter" ("personId");
