-- People: the page a company has, for a senator, a representative, a
-- member of the executive branch, a governor or another major political
-- figure (/person/<slug>). What the page shows is only what a source says:
-- every personal fact, figure and contribution carries the URL it was read
-- from, and a field nobody has published stays NULL and is left off the page
-- (never "unknown", never a guess). Health, weight and religion are listed only
-- where the person has disclosed them or a reputable outlet has reported them.
-- Filled by `npm run people:import` (GovTrack + Wikidata, keyless) and by
-- hand with `npm run people:apply`; prod stores what a local run sends it
-- (PUT /api/people/:id, admin only).
CREATE TABLE "Person" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- The name as it is written ("Susan Collins"); the page's URL word is its
  -- topicSlug (src/lib/topics.ts), unique here so two people never share one.
  "name"               varchar(200) NOT NULL,
  "slug"               varchar(200) NOT NULL CONSTRAINT "UC_Person_slug" UNIQUE,
  -- 'president', 'vice-president', 'cabinet' (a department head or other
  -- member of the executive branch), 'senator', 'representative', 'governor',
  -- 'other' (a mayor, a speaker's staff, a former official still in the news).
  "role"               varchar(20) NOT NULL DEFAULT 'other',
  -- "United States Senator from Maine", as the office is written.
  "office"             varchar(200),
  -- Where the office is: "Maine", "United States".
  "jurisdiction"       varchar(120),
  "party"              varchar(80),
  -- What the person stands for in a line, from a source ("Moderate
  -- Republican; Appropriations Committee chair"), with where it was read.
  "politics"           text,
  "politicsSourceUrl"  text,
  "inOfficeSince"      date,
  "birthDate"          date,
  "deathDate"          date,
  "religion"           varchar(120),
  "religionSourceUrl"  text,
  -- Kilograms, when the person or their physician has published it (a
  -- presidential physical, a campaign biography), with the day it was read
  -- for. A weight that was never published is not estimated.
  "weightKg"           numeric(5,1) CONSTRAINT "CK_Person_weight" CHECK ("weightKg" IS NULL OR "weightKg" BETWEEN 25 AND 400),
  "weightAsOf"         date,
  "weightSourceUrl"    text,
  -- A line on health the person has made public (a surgery, a physician's
  -- letter, a diagnosis they announced), as of a day, from a source.
  "health"             text,
  "healthAsOf"         date,
  "healthSourceUrl"    text,
  "description"        text,
  "photoUrl"           text,
  "photoCredit"        text,
  "wikiUrl"            text,
  "websiteUrl"         text,
  -- The ids the importers match on: Congress's bioguide id (a member of
  -- Congress, or a past one who became a governor or cabinet member), GovTrack's
  -- person id and Wikidata's Q-id.
  "bioguideId"         varchar(12) CONSTRAINT "UC_Person_bioguideId" UNIQUE,
  "govtrackId"         integer CONSTRAINT "UC_Person_govtrackId" UNIQUE,
  "wikidataId"         varchar(16) CONSTRAINT "UC_Person_wikidataId" UNIQUE,
  -- When `people:import --laws` last read the member's sponsored bills.
  "utcLawsCheckedDateTime" timestamptz,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  "utcUpdatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_Person_role" CHECK ("role" IN ('president', 'vice-president', 'cabinet', 'senator', 'representative', 'governor', 'other')),
  CONSTRAINT "CK_Person_death" CHECK ("deathDate" IS NULL OR "birthDate" IS NULL OR "deathDate" >= "birthDate")
);
CREATE INDEX "IX_Person_role" ON "Person" ("role");

-- What the person earned in a calendar year, one row per source of it: the
-- salary the office pays, and income the financial disclosure reports on top
-- (book royalties, speaking fees, a spouse's job where it is reported
-- jointly). The page shows one tile per year with the rows behind its total.
-- A range a disclosure gives ("$100,001 - $1,000,000") is kept as low/high.
CREATE TABLE "PersonEarning" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"       integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "year"               smallint NOT NULL CONSTRAINT "CK_PersonEarning_year" CHECK ("year" BETWEEN 1950 AND 2100),
  -- 'salary', 'outside-income' (earned outside the office), 'royalties',
  -- 'investments' (dividends, interest, capital gains), 'pension', 'other'.
  "kind"               varchar(16) NOT NULL DEFAULT 'salary',
  -- What the line is ("Senate salary", "Book royalties - Simon & Schuster").
  "label"              varchar(200) NOT NULL DEFAULT '',
  -- Whole units of `currency`. A range keeps both ends and `amount` is NULL.
  "amount"             bigint CONSTRAINT "CK_PersonEarning_amount" CHECK ("amount" >= 0),
  "amountLow"          bigint CONSTRAINT "CK_PersonEarning_low" CHECK ("amountLow" >= 0),
  "amountHigh"         bigint CONSTRAINT "CK_PersonEarning_high" CHECK ("amountHigh" >= 0),
  "currency"           char(3) NOT NULL DEFAULT 'USD',
  "sourceUrl"          text,
  "note"               text,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonEarning_kind" CHECK ("kind" IN ('salary', 'outside-income', 'royalties', 'investments', 'pension', 'other')),
  CONSTRAINT "CK_PersonEarning_figure" CHECK ("amount" IS NOT NULL OR ("amountLow" IS NOT NULL AND "amountHigh" IS NOT NULL)),
  CONSTRAINT "UC_PersonEarning_year_kind_label" UNIQUE ("personId", "year", "kind", "label")
);
CREATE INDEX "IX_PersonEarning_personId" ON "PersonEarning" ("personId", "year" DESC);

-- The laws a person passed and the other things they are known for: a law
-- they sponsored or signed, a bill that did not pass but defined their
-- career, an executive order, a committee they chaired, an office held, a
-- campaign or an award. `kind = 'law'` is the section the page leads with.
CREATE TABLE "PersonContribution" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"       integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  -- 'law' (enacted), 'bill' (introduced, not enacted), 'executive-order',
  -- 'committee', 'office' (a post held), 'initiative', 'award', 'other'.
  "kind"               varchar(20) NOT NULL DEFAULT 'law',
  "title"              varchar(400) NOT NULL,
  "summary"            text,
  -- 'sponsor', 'cosponsor', 'signed' (by a president or governor), 'author',
  -- 'chair', 'member', 'led'.
  "role"               varchar(16),
  "date"               date,
  -- "Pub. L. 117-169", "H.R. 5376", "E.O. 14017": the citation.
  "reference"          varchar(120),
  -- 1 is the career-defining one; the page lists lowest first, then newest.
  "importance"         smallint NOT NULL DEFAULT 3 CONSTRAINT "CK_PersonContribution_importance" CHECK ("importance" BETWEEN 1 AND 5),
  "sourceUrl"          text,
  "origin"             varchar(10) NOT NULL DEFAULT 'hand',
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonContribution_kind" CHECK ("kind" IN ('law', 'bill', 'executive-order', 'committee', 'office', 'initiative', 'award', 'other')),
  CONSTRAINT "CK_PersonContribution_origin" CHECK ("origin" IN ('congress', 'wikidata', 'hand')),
  CONSTRAINT "UC_PersonContribution_kind_title_ref" UNIQUE ("personId", "kind", "title", "reference")
);
CREATE INDEX "IX_PersonContribution_personId" ON "PersonContribution" ("personId", "kind");

-- Houses and land the person owns or has owned, from their financial
-- disclosure, the property record or reporting. `valueLow`/`valueHigh` are a
-- disclosure's value range, or the sale price twice.
CREATE TABLE "PersonProperty" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"       integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "name"               varchar(200) NOT NULL,
  -- 'residence', 'second-home', 'investment', 'land', 'other'.
  "kind"               varchar(12) NOT NULL DEFAULT 'residence',
  "location"           varchar(200),
  "valueLow"           bigint CONSTRAINT "CK_PersonProperty_low" CHECK ("valueLow" >= 0),
  "valueHigh"          bigint CONSTRAINT "CK_PersonProperty_high" CHECK ("valueHigh" >= 0),
  "currency"           char(3) NOT NULL DEFAULT 'USD',
  "acquiredYear"       smallint,
  -- The day the value is read for (a disclosure's reporting year-end).
  "asOf"               date,
  "sourceUrl"          text,
  "note"               text,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonProperty_kind" CHECK ("kind" IN ('residence', 'second-home', 'investment', 'land', 'other')),
  CONSTRAINT "UC_PersonProperty_name" UNIQUE ("personId", "name")
);
CREATE INDEX "IX_PersonProperty_personId" ON "PersonProperty" ("personId");

-- Trips the person took, newest first on the page: the leisure ones, and the
-- privately paid ones a disclosure reports. `kind = 'leisure'` is a holiday
-- reported by an outlet or the person's own posts; 'sponsored' is travel paid
-- for by an outside group (Congress files these); 'official' is a government
-- trip, kept so the page can tell it from a holiday.
CREATE TABLE "PersonTrip" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "personId"       integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  "destination"        varchar(200) NOT NULL,
  "kind"               varchar(12) NOT NULL DEFAULT 'leisure',
  "startDate"          date NOT NULL,
  "endDate"            date,
  "sourceUrl"          text,
  "note"               text,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "CK_PersonTrip_kind" CHECK ("kind" IN ('leisure', 'sponsored', 'official')),
  CONSTRAINT "CK_PersonTrip_dates" CHECK ("endDate" IS NULL OR "endDate" >= "startDate"),
  CONSTRAINT "UC_PersonTrip_destination_start" UNIQUE ("personId", "destination", "startDate")
);
CREATE INDEX "IX_PersonTrip_personId" ON "PersonTrip" ("personId", "startDate" DESC);

-- Pins about a person (a vote, a signing, a hearing, an election), shown on
-- the person's page like a company's pins. Linked by `people:link-pins`
-- from the pin tags that carry the person's name, and by hand.
CREATE TABLE "PinPerson" (
  "pinId"        integer NOT NULL REFERENCES "Pin" ("id") ON DELETE CASCADE,
  "personId" integer NOT NULL REFERENCES "Person" ("id") ON DELETE CASCADE,
  PRIMARY KEY ("pinId", "personId")
);
CREATE INDEX "IX_PinPerson_personId" ON "PinPerson" ("personId");
