-- Saved searches with alerts: a reader keeps a search query (the same text the
-- search box takes: date:, place:, holiday:, person:, free text) and is told
-- when a new pin matches it - in the bell, and in the Monday digest email.
--
-- A timer sweeps the live searches: every pin created since the search was
-- last checked that it matches is one "SearchAlertMatch" row. The primary key
-- is what keeps a pin to one notification per search however many servers
-- see it due, and what the digest reads back for its week.

CREATE TABLE "SearchAlert" (
  "id"                    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"                integer NOT NULL REFERENCES "User" ("id") ON DELETE CASCADE,
  -- The query exactly as typed, so a relative term (date:today) stays relative.
  "query"                 varchar(500) NOT NULL,
  -- The name the reader gave it; null shows the query.
  "label"                 varchar(120),
  "notifyBell"            boolean NOT NULL DEFAULT true,
  "notifyDigest"          boolean NOT NULL DEFAULT true,
  -- Pins created after this have not been matched against the search yet.
  "utcLastCheckedDateTime" timestamptz NOT NULL DEFAULT now(),
  "utcCreatedDateTime"    timestamptz NOT NULL DEFAULT now(),
  "utcDeletedDateTime"    timestamptz
);
CREATE INDEX "IX_SearchAlert_user" ON "SearchAlert" ("userId") WHERE "utcDeletedDateTime" IS NULL;
CREATE INDEX "IX_SearchAlert_check" ON "SearchAlert" ("utcLastCheckedDateTime") WHERE "utcDeletedDateTime" IS NULL;
-- One live search per reader and query (ignoring case and spacing).
CREATE UNIQUE INDEX "UX_SearchAlert_query" ON "SearchAlert" ("userId", lower(btrim("query"))) WHERE "utcDeletedDateTime" IS NULL;

CREATE TABLE "SearchAlertMatch" (
  "searchAlertId"      integer NOT NULL REFERENCES "SearchAlert" ("id") ON DELETE CASCADE,
  "pinId"              integer NOT NULL REFERENCES "Pin" ("id") ON DELETE CASCADE,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY ("searchAlertId", "pinId")
);
CREATE INDEX "IX_SearchAlertMatch_recent" ON "SearchAlertMatch" ("utcCreatedDateTime");

-- A 'search' notification says which saved search it is for.
ALTER TABLE "Notification" ADD COLUMN "searchAlertId" integer REFERENCES "SearchAlert" ("id") ON DELETE CASCADE;
CREATE UNIQUE INDEX "UX_Notification_search" ON "Notification" ("userId", "searchAlertId", "pinId") WHERE "type" = 'search';
