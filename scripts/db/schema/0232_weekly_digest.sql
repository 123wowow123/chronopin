-- The weekly "my timeline" email: what is coming up in the next seven days
-- from the pins a user watches and the companies and people they follow.
--
-- Opt-in: a user is sent it only with an enabled "DigestSubscription" row
-- (the toggle on /profile/notifications, or the unsubscribe link in the email
-- turning it off). One "DigestSend" row per user per week is the claim that
-- keeps it to one email however many servers see it due, and what the admin
-- Digest page counts. "DigestClick" is one row per link followed from it.

CREATE TABLE "DigestSubscription" (
  "userId"             integer PRIMARY KEY REFERENCES "User" ("id") ON DELETE CASCADE,
  "enabled"            boolean NOT NULL DEFAULT true,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now(),
  "utcUpdatedDateTime" timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE "DigestSend" (
  "id"                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "userId"              integer NOT NULL REFERENCES "User" ("id") ON DELETE CASCADE,
  -- The Monday (UTC) of the week it was for.
  "weekStart"           date NOT NULL,
  -- pending (claimed, being built), sent, skipped (nothing coming up) or failed.
  "status"              varchar(12) NOT NULL DEFAULT 'pending' CHECK ("status" IN ('pending', 'sent', 'skipped', 'failed')),
  "watchedCount"        integer NOT NULL DEFAULT 0,
  "companyCount"        integer NOT NULL DEFAULT 0,
  "followedCount"       integer NOT NULL DEFAULT 0,
  "pinCount"            integer NOT NULL DEFAULT 0,
  "error"               varchar(500),
  "openCount"           integer NOT NULL DEFAULT 0,
  "clickCount"          integer NOT NULL DEFAULT 0,
  "utcCreatedDateTime"  timestamptz NOT NULL DEFAULT now(),
  "utcSentDateTime"     timestamptz,
  "utcOpenedDateTime"   timestamptz,
  "utcClickedDateTime"  timestamptz,
  CONSTRAINT "UC_DigestSend_week" UNIQUE ("userId", "weekStart")
);
CREATE INDEX "IX_DigestSend_week" ON "DigestSend" ("weekStart");

CREATE TABLE "DigestClick" (
  "id"                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "sendId"             integer NOT NULL REFERENCES "DigestSend" ("id") ON DELETE CASCADE,
  "path"               varchar(500) NOT NULL,
  "utcCreatedDateTime" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX "IX_DigestClick_send" ON "DigestClick" ("sendId");
