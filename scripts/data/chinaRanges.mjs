// Regenerates src/server/chinaRanges.ts from APNIC's delegation file:
//   node scripts/data/chinaRanges.mjs [path-to-delegated-apnic-latest]
// Without a path it downloads https://ftp.apnic.net/stats/apnic/delegated-apnic-latest.
import fs from 'node:fs';

const file = process.argv[2];
const text = file ? fs.readFileSync(file, 'utf8') : await (await fetch('https://ftp.apnic.net/stats/apnic/delegated-apnic-latest')).text();

const v4 = [];
const v6 = [];
for (const line of text.split('\n')) {
  const f = line.split('|');
  if (f[0] !== 'apnic' || f[1] !== 'CN') continue;
  if (f[2] === 'ipv4') {
    const start = f[3].split('.').reduce((n, o) => n * 256 + Number(o), 0);
    v4.push([start, start + Number(f[4]) - 1]);
  } else if (f[2] === 'ipv6') {
    // Every CN allocation is /64 or shorter: keep the top 64 bits.
    const bits = BigInt(f[4]);
    const hextets = f[3].split('::')[0].split(':').filter(Boolean);
    let start = 0n;
    for (let i = 0; i < 4; i++) start = (start << 16n) | BigInt(parseInt(hextets[i] ?? '0', 16));
    v6.push([start, start + (1n << (64n - bits)) - 1n]);
  }
}

function merge(ranges) {
  ranges.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const out = [];
  for (const r of ranges) {
    const last = out[out.length - 1];
    if (last && r[0] <= last[1] + (typeof r[0] === 'bigint' ? 1n : 1)) {
      if (r[1] > last[1]) last[1] = r[1];
    } else out.push([...r]);
  }
  return out;
}

const m4 = merge(v4);
const m6 = merge(v6);
const body = `// Mainland China's IP allocations, from APNIC's delegation file (generated by
// scripts/data/chinaRanges.mjs on ${new Date().toISOString().slice(0, 10)}; rerun it to refresh). IPv4 ranges are
// flat [start, end, ...] numbers; IPv6 ranges are the top 64 bits in hex as
// "start-end". Both sorted and merged, for a binary search.
export const CHINA_V4: number[] = [${m4.flat().join(',')}];
export const CHINA_V6: string[] = [${m6.map(([a, b]) => `'${a.toString(16)}-${b.toString(16)}'`).join(',')}];
`;
fs.writeFileSync(new URL('../../src/server/chinaRanges.ts', import.meta.url), body);
console.log(`${m4.length} IPv4 ranges, ${m6.length} IPv6 ranges`);
