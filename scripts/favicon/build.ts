// Renders the header logo into src/app/favicon.ico (16/32/48px PNG frames),
// which the App Router serves automatically, into public/apple-touch-icon.png
// (what an iPhone shows for a saved or shared link), and into the PNG the
// account emails carry inline (src/server/emailLogo.ts: mail clients show no SVG),
// and into public/icons/ (the installed app's icons and the notification badge, src/app/manifest.ts). It
// renders the LogoMark component itself, so neither can drift from the logo;
// rerun after changing it.
//
//   npm run favicon:build
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import sharp from 'sharp';
import { LogoMark } from '../../src/components/ui/LogoMark';

const APP = resolve(import.meta.dirname, '../../src/app');
const ICO_SIZES = [16, 32, 48];

// The logo's 32-unit box leaves the cluster (x 0.7–30.5, y 4.3–31.5) off
// centre, so the icon uses a square viewBox around it instead.
const VIEWBOX = '0 2.3 31.2 31.2';
const svg = renderToStaticMarkup(createElement(LogoMark)).replace(
  /^<svg viewBox="[^"]*"/,
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${VIEWBOX}"`,
);
if (!svg.includes(VIEWBOX)) throw new Error(`LogoMark no longer starts <svg viewBox=…>: ${svg.slice(0, 80)}`);

// An .ico is a 6-byte header, a 16-byte directory entry per image, then the
// images; PNG-encoded frames are supported by every browser and Windows Vista+.
function ico(pngs: { size: number; data: Buffer }[]) {
  const header = Buffer.alloc(6 + 16 * pngs.length);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  let offset = header.length;
  pngs.forEach(({ size, data }, i) => {
    const entry = 6 + 16 * i;
    header[entry] = size % 256;
    header[entry + 1] = size % 256;
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...pngs.map((p) => p.data)]);
}

const pngs = await Promise.all(
  ICO_SIZES.map(async (size) => ({
    size,
    data: await sharp(Buffer.from(svg), { density: (72 * size) / 31.2 * 4 }).resize(size, size).png().toBuffer(),
  })),
);

writeFileSync(resolve(APP, 'favicon.ico'), ico(pngs));
console.log(`Wrote favicon.ico (${ICO_SIZES.join('/')}px) to ${APP}`);

// iOS wants 180px, square and opaque (it fills transparency with black), so
// the logo sits on the dark page colour with a margin.
const TOUCH_SIZE = 180;
const TOUCH_LOGO = 128;
const touchLogo = await sharp(Buffer.from(svg), { density: ((72 * TOUCH_LOGO) / 31.2) * 4 }).resize(TOUCH_LOGO, TOUCH_LOGO).png().toBuffer();
const touch = await sharp({ create: { width: TOUCH_SIZE, height: TOUCH_SIZE, channels: 4, background: '#111111' } })
  .composite([{ input: touchLogo, gravity: 'centre' }])
  .png()
  .toBuffer();
writeFileSync(resolve(APP, '../../public/apple-touch-icon.png'), touch);
console.log(`Wrote the ${TOUCH_SIZE}px apple-touch-icon.png to public/`);

// Shown at 48px; drawn at twice that for high-density screens.
const EMAIL_LOGO_SIZE = 96;
const emailLogo = await sharp(Buffer.from(svg), { density: ((72 * EMAIL_LOGO_SIZE) / 31.2) * 4 }).resize(EMAIL_LOGO_SIZE, EMAIL_LOGO_SIZE).png().toBuffer();
writeFileSync(
  resolve(APP, '../server/emailLogo.ts'),
  `// Generated by npm run favicon:build from LogoMark: the ${EMAIL_LOGO_SIZE}px PNG the account\n` +
    `// emails show inline (src/server/emailVerification.ts). Do not edit by hand.\n` +
    `export const EMAIL_LOGO_PNG_BASE64 =\n  '${emailLogo.toString('base64')}';\n`,
);
console.log(`Wrote the ${EMAIL_LOGO_SIZE}px email logo to src/server/emailLogo.ts`);

// The installed app (src/app/manifest.ts). Android crops a "maskable" icon to
// whatever shape the launcher uses, keeping only the central 80% circle, so
// that one carries the logo smaller; the plain ones fill more of the tile.
const ICONS = resolve(APP, '../../public/icons');
mkdirSync(ICONS, { recursive: true });
const PAGE = '#111111';
async function tile(size: number, logoShare: number, source = svg, background: string | { r: number; g: number; b: number; alpha: number } = PAGE) {
  const logoSize = Math.round(size * logoShare);
  const logo = await sharp(Buffer.from(source), { density: ((72 * logoSize) / 31.2) * 4 }).resize(logoSize, logoSize).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background } })
    .composite([{ input: logo, gravity: 'centre' }])
    .png()
    .toBuffer();
}
writeFileSync(resolve(ICONS, 'icon-192.png'), await tile(192, 0.72));
writeFileSync(resolve(ICONS, 'icon-512.png'), await tile(512, 0.72));
writeFileSync(resolve(ICONS, 'icon-maskable-512.png'), await tile(512, 0.5));
// The Android status bar draws a badge as a mask of its alpha channel, so it is
// the logo's silhouette on nothing.
const silhouette = svg.replace(/fill="#[0-9a-f]{6}"/gi, 'fill="#ffffff"');
writeFileSync(resolve(ICONS, 'badge-96.png'), await tile(96, 0.9, silhouette, { r: 0, g: 0, b: 0, alpha: 0 }));
console.log('Wrote icon-192/512, icon-maskable-512 and badge-96 to public/icons/');
